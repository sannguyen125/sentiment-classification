"""Build reports/BAO_CAO.docx from reports/BAO_CAO.md (pandoc via pypandoc_binary + python-docx).

Run: python reports/build_docx.py          (Word is not needed)
- LaTeX math ($...$, $$...$$) becomes native Word equations; images are read relative to reports/
  (the Markdown points to ../results/figures/).
- Styles come from reports/template/reference.docx. If that file is missing, or is the one this
  script generated earlier, it is (re)built from pandoc's default reference.docx: A4, Times New
  Roman 13 for text and headings, line spacing 1.3, margins top/bottom 2 cm, left 3 cm, right 2 cm,
  black headings, justified paragraphs, page number centred in the footer. A reference.docx that
  someone put there by hand (e.g. the PTIT template) is used as it is.
- After pandoc: cover in its own section (PTIT layout from the template PDF: double frame, logo,
  borderless info block, no page number), work-division table, Word TOC field (Word refreshes it on
  opening), page breaks (before the TOC and every level-1 heading), bordered tables with 12 pt
  text, centred images no wider than the text block.
"""
import copy
import subprocess
import sys
from pathlib import Path

import pypandoc
from docx import Document
from docx.enum.section import WD_ORIENT
from docx.enum.style import WD_STYLE_TYPE
from docx.enum.text import WD_ALIGN_PARAGRAPH, WD_LINE_SPACING
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Cm, Pt, RGBColor
from docx.text.paragraph import Paragraph

REPORTS = Path(__file__).resolve().parent
MD = REPORTS / "BAO_CAO.md"
OUT = REPORTS / "BAO_CAO.docx"
REF = REPORTS / "template" / "reference.docx"
AUTO_MARK = "auto-generated by reports/build_docx.py"
FONT = "Times New Roman"
BODY_PT, TABLE_PT, LINE = 13, 12, 1.3
COVER = {  # custom-style name in the Markdown -> (size pt, bold, space before pt, space after pt)
    "CoverSchool": (14, True, 0, 4), "CoverLine": (14, False, 0, 14), "CoverLogo": (14, False, 0, 26),
    "CoverReport": (20, True, 0, 6), "CoverTitle": (18, True, 0, 28), "CoverDate": (14, True, 165, 0),
    "FrontTitle": (14, True, 0, 12),
}
COVER_FIRST_GAP = {"CoverSchool": 22}  # extra space before the first paragraph of the style
COVER_PT = 14  # text of the info block on the cover
COVER_MARGIN_CM = 2.5  # symmetric margins of the cover section
# double frame of the PTIT cover: thick outside, thin inside, about 1.5 cm from the paper edge
FRAME = {"top": "thickThinLargeGap", "left": "thickThinLargeGap",
         "bottom": "thinThickLargeGap", "right": "thinThickLargeGap"}
FRAME_SZ, FRAME_SPACE_PT = 12, 28


# ---------------------------------------------------------------- reference.docx
def _set_fonts(style, size: float | None = None, bold: bool | None = None, black: bool = True) -> None:
    rpr = style.element.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = OxmlElement("w:rFonts")
        rpr.insert(0, rfonts)
    for attr in list(rfonts.attrib):  # drop theme fonts, they override the font name
        del rfonts.attrib[attr]
    for attr in ("w:ascii", "w:hAnsi", "w:cs", "w:eastAsia"):
        rfonts.set(qn(attr), FONT)
    if size:
        style.font.size = Pt(size)
    if bold is not None:
        style.font.bold = bold
    if black:
        style.font.color.rgb = RGBColor(0, 0, 0)
        color = rpr.find(qn("w:color"))
        for attr in ("w:themeColor", "w:themeShade", "w:themeTint"):
            if color is not None and color.get(qn(attr)) is not None:
                del color.attrib[qn(attr)]


def _page_setup(section) -> None:
    section.orientation = WD_ORIENT.PORTRAIT
    section.page_width, section.page_height = Cm(21), Cm(29.7)
    section.top_margin, section.bottom_margin = Cm(2), Cm(2)
    section.left_margin, section.right_margin = Cm(3), Cm(2)


def _add_page_field(paragraph) -> None:
    for kind, text in (("begin", None), (None, "PAGE"), ("separate", None), (None, "1"), ("end", None)):
        run = paragraph.add_run()
        if kind:
            fld = OxmlElement("w:fldChar")
            fld.set(qn("w:fldCharType"), kind)
            run._r.append(fld)
        elif text == "PAGE":
            instr = OxmlElement("w:instrText")
            instr.set(qn("xml:space"), "preserve")
            instr.text = " PAGE "
            run._r.append(instr)
        else:
            run.text = text


def _footer_page_number(section) -> None:
    section.different_first_page_header_footer = True  # no number on the cover
    footer = section.footer
    footer.is_linked_to_previous = False
    p = footer.paragraphs[0] if footer.paragraphs else footer.add_paragraph()
    if "PAGE" in p._p.xml:
        return
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    _add_page_field(p)


def build_reference() -> None:
    REF.parent.mkdir(parents=True, exist_ok=True)
    data = subprocess.run([pypandoc.get_pandoc_path(), "--print-default-data-file", "reference.docx"],
                          capture_output=True, check=True).stdout
    REF.write_bytes(data)
    doc = Document(REF)
    for st in doc.styles:
        if st.type == WD_STYLE_TYPE.PARAGRAPH:
            caption = st.name in ("Table Caption", "Image Caption", "Caption")
            _set_fonts(st, TABLE_PT if caption else BODY_PT)
        elif st.type == WD_STYLE_TYPE.CHARACTER and st.name not in ("Verbatim Char",):
            _set_fonts(st, black=st.name != "Hyperlink")
    normal = doc.styles["Normal"].paragraph_format
    normal.line_spacing_rule, normal.line_spacing = WD_LINE_SPACING.MULTIPLE, LINE
    for name in ("Body Text", "First Paragraph", "Compact"):
        pf = doc.styles[name].paragraph_format
        pf.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        pf.line_spacing_rule, pf.line_spacing = WD_LINE_SPACING.MULTIPLE, LINE
        pf.space_before, pf.space_after = Pt(0), Pt(6)
    for level in range(1, 4):
        st = doc.styles[f"Heading {level}"]
        _set_fonts(st, BODY_PT, bold=True)
        st.font.italic = level == 3
        pf = st.paragraph_format
        pf.alignment = WD_ALIGN_PARAGRAPH.LEFT
        pf.line_spacing_rule, pf.line_spacing = WD_LINE_SPACING.MULTIPLE, LINE
        pf.space_before, pf.space_after = Pt(12 if level > 1 else 0), Pt(6)
        pf.keep_with_next = True
        pf.page_break_before = level == 1
    for name in ("Table Caption", "Image Caption"):
        st = doc.styles[name]
        st.font.italic = True
        pf = st.paragraph_format
        pf.alignment = WD_ALIGN_PARAGRAPH.CENTER
        pf.space_before, pf.space_after = Pt(6), Pt(10)
    doc.styles["Table Caption"].paragraph_format.keep_with_next = True
    for section in doc.sections:
        _page_setup(section)
        _footer_page_number(section)
    doc.core_properties.comments = AUTO_MARK
    doc.save(REF)
    print("reference.docx built:", REF.relative_to(REPORTS.parent))


def ensure_reference() -> None:
    if REF.exists() and Document(REF).core_properties.comments != AUTO_MARK:
        print("using template:", REF.relative_to(REPORTS.parent))
        return
    build_reference()


# ---------------------------------------------------------------- pandoc
def run_pandoc() -> None:
    args = [pypandoc.get_pandoc_path(), MD.name, "-f",
            "markdown+tex_math_dollars+pipe_tables+fenced_divs+implicit_figures+link_attributes",
            "-t", "docx", f"--reference-doc={REF}", f"--resource-path={REPORTS}",
            "--columns=20",  # pipe tables: column widths follow the dashes of the separator row
            "-o", str(OUT)]
    subprocess.run(args, cwd=REPORTS, check=True)


# ---------------------------------------------------------------- post-processing
def _style(doc, name: str):
    try:
        return doc.styles[name]
    except KeyError:
        return None


def format_cover(doc) -> None:
    seen = set()
    for name, (size, bold, before, after) in COVER.items():
        st = _style(doc, name)
        if st is None:
            continue
        _set_fonts(st, size, bold=bold)
        pf = st.paragraph_format
        pf.alignment = WD_ALIGN_PARAGRAPH.CENTER
        pf.space_before, pf.space_after = Pt(before), Pt(after)
        pf.line_spacing_rule, pf.line_spacing = WD_LINE_SPACING.MULTIPLE, 1.15
        pf.first_line_indent = Cm(0)
    for p in doc.paragraphs:
        name = p.style.name if p.style is not None else ""
        if name in COVER_FIRST_GAP and name not in seen:
            p.paragraph_format.space_before = Pt(COVER_FIRST_GAP[name])
            seen.add(name)


def _run(text: str | None = None, fld: str | None = None, instr: str | None = None):
    r = OxmlElement("w:r")
    if fld:
        el = OxmlElement("w:fldChar")
        el.set(qn("w:fldCharType"), fld)
        if fld == "begin":
            el.set(qn("w:dirty"), "true")  # Word recomputes the TOC (page numbers) on opening
        r.append(el)
    elif instr:
        el = OxmlElement("w:instrText")
        el.set(qn("xml:space"), "preserve")
        el.text = instr
        r.append(el)
    else:
        t = OxmlElement("w:t")
        t.set(qn("xml:space"), "preserve")
        t.text = text
        r.append(t)
    return r


def _paragraph(runs: list, indent_cm: float = 0, center: bool = False, bold: bool = False,
               size: float | None = None, page_break: bool = False):
    p = OxmlElement("w:p")
    ppr = OxmlElement("w:pPr")
    if page_break:
        ppr.append(OxmlElement("w:pageBreakBefore"))
    if indent_cm:
        ind = OxmlElement("w:ind")
        ind.set(qn("w:left"), str(int(indent_cm * 567)))
        ppr.append(ind)
    if center:
        jc = OxmlElement("w:jc")
        jc.set(qn("w:val"), "center")
        ppr.append(jc)
    p.append(ppr)
    for r in runs:
        if bold or size:
            rpr = OxmlElement("w:rPr")
            if bold:
                rpr.append(OxmlElement("w:b"))
            if size:
                sz = OxmlElement("w:sz")
                sz.set(qn("w:val"), str(int(size * 2)))
                rpr.append(sz)
            r.insert(0, rpr)
        p.append(r)
    return p


def insert_toc(doc) -> None:
    heads = [(int(p.style.name[-1]), p.text.strip()) for p in doc.paragraphs
             if p.style is not None and p.style.name in ("Heading 1", "Heading 2", "Heading 3") and p.text.strip()]
    first_h1 = next(p for p in doc.paragraphs if p.style is not None and p.style.name == "Heading 1")
    anchor = first_h1._p
    anchor.addprevious(_paragraph([_run("MỤC LỤC")], center=True, bold=True, size=14, page_break=True))
    # field result = headings without page numbers until Word updates the field
    for i, (level, text) in enumerate(heads):
        runs = []
        if i == 0:
            runs += [_run(fld="begin"), _run(instr=' TOC \\o "1-3" \\h \\z \\u '), _run(fld="separate")]
        runs.append(_run(text))
        if i == len(heads) - 1:
            runs.append(_run(fld="end"))
        anchor.addprevious(_paragraph(runs, indent_cm=0.6 * (level - 1)))
    settings = doc.settings.element
    if settings.find(qn("w:updateFields")) is None:
        upd = OxmlElement("w:updateFields")
        upd.set(qn("w:val"), "true")
        settings.append(upd)


def page_breaks(doc) -> None:
    for p in doc.paragraphs:
        if p.style is not None and p.style.name == "Heading 1":
            p.paragraph_format.page_break_before = True


TBLPR_ORDER = ["tblStyle", "tblpPr", "tblOverlap", "bidiVisual", "tblStyleRowBandSize", "tblStyleColBandSize",
               "tblW", "jc", "tblCellSpacing", "tblInd", "tblBorders", "shd", "tblLayout", "tblCellMar",
               "tblLook", "tblCaption", "tblDescription"]  # schema order of w:tblPr children


def _set_tblpr(tblpr, el) -> None:
    """Replace or insert a w:tblPr child at its schema position (Word ignores out-of-order children)."""
    name = el.tag.split("}")[1]
    old = tblpr.find(qn(f"w:{name}"))
    if old is not None:
        tblpr.remove(old)
    after = TBLPR_ORDER[TBLPR_ORDER.index(name) + 1:]
    nxt = next((c for c in tblpr if c.tag.split("}")[1] in after), None)
    if nxt is None:
        tblpr.append(el)
    else:
        nxt.addprevious(el)


def _borders(table) -> None:
    tblpr = table._tbl.tblPr
    borders = OxmlElement("w:tblBorders")
    for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
        el = OxmlElement(f"w:{edge}")
        el.set(qn("w:val"), "single")
        el.set(qn("w:sz"), "4")
        el.set(qn("w:space"), "0")
        el.set(qn("w:color"), "000000")
        borders.append(el)
    _set_tblpr(tblpr, borders)
    jc = OxmlElement("w:jc")
    jc.set(qn("w:val"), "center")
    _set_tblpr(tblpr, jc)


def _full_width(table, width_twips: int) -> None:
    """pandoc sizes the grid for its own page width; rescale the columns to the text block."""
    cols = table._tbl.tblGrid.findall(qn("w:gridCol"))
    total = sum(int(c.get(qn("w:w"))) for c in cols)
    if not total:
        return
    for c in cols:
        c.set(qn("w:w"), str(round(int(c.get(qn("w:w"))) * width_twips / total)))


def _in_cover(doc, table) -> bool:
    """True for a table placed before the end of the cover (the CoverDate paragraph)."""
    for el in doc.element.body:
        if el is table._tbl:
            return True
        style = el.find(qn("w:pPr") + "/" + qn("w:pStyle")) if el.tag == qn("w:p") else None
        if style is not None and style.get(qn("w:val")) == "CoverDate":
            return False
    return False


def format_cover_table(table, width_twips: int) -> None:
    """Info block of the cover: no borders, right-aligned label, value at the page centre line."""
    borders = OxmlElement("w:tblBorders")
    for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
        el = OxmlElement(f"w:{edge}")
        el.set(qn("w:val"), "nil")
        borders.append(el)
    _set_tblpr(table._tbl.tblPr, borders)
    _full_width(table, width_twips)
    for row in table.rows:
        for c_i, cell in enumerate(row.cells):
            for p in cell.paragraphs:
                pf = p.paragraph_format
                pf.alignment = WD_ALIGN_PARAGRAPH.RIGHT if c_i == 0 else WD_ALIGN_PARAGRAPH.LEFT
                pf.space_before, pf.space_after = Pt(3), Pt(3)
                pf.line_spacing_rule, pf.line_spacing = WD_LINE_SPACING.MULTIPLE, 1.0
                for run in p.runs:
                    run.font.size = Pt(COVER_PT)


def format_tables(doc) -> None:
    sec = doc.sections[0]
    text_twips = int((sec.page_width - sec.left_margin - sec.right_margin) / 635)  # EMU -> twips
    for table in doc.tables:
        if _in_cover(doc, table):
            format_cover_table(table, text_twips)
            continue
        _borders(table)
        _full_width(table, text_twips)
        last = len(table.rows) - 1
        for r_i, row in enumerate(table.rows):
            trpr = row._tr.get_or_add_trPr()
            if trpr.find(qn("w:cantSplit")) is None:
                trpr.append(OxmlElement("w:cantSplit"))
            for cell in row.cells:
                for p in cell.paragraphs:
                    pf = p.paragraph_format
                    pf.keep_with_next = r_i < last  # keep the whole table on one page
                    pf.space_before, pf.space_after = Pt(2), Pt(2)
                    pf.line_spacing_rule, pf.line_spacing = WD_LINE_SPACING.MULTIPLE, 1.0
                    if pf.alignment == WD_ALIGN_PARAGRAPH.JUSTIFY or pf.alignment is None:
                        pf.alignment = WD_ALIGN_PARAGRAPH.LEFT if p.alignment is None else p.alignment
                    for run in p.runs:
                        run.font.size = Pt(TABLE_PT)
                        if r_i == 0:
                            run.font.bold = True
                    for m in p._p.iter(qn("m:r")):  # equations inside tables
                        rpr = m.find(qn("w:rPr"))
                        if rpr is None:
                            rpr = OxmlElement("w:rPr")
                            m.insert(0, rpr)
                        sz = OxmlElement("w:sz")
                        sz.set(qn("w:val"), str(TABLE_PT * 2))
                        rpr.append(sz)
        nxt = table._tbl.getnext()  # breathing space between a table and the text after it
        if nxt is not None and nxt.tag == qn("w:p"):
            Paragraph(nxt, table._parent).paragraph_format.space_before = Pt(8)


def format_images(doc) -> None:
    sec = doc.sections[0]
    max_w = sec.page_width - sec.left_margin - sec.right_margin
    for p in doc.paragraphs:
        inlines = p._p.findall(".//" + qn("wp:inline"))
        if not inlines:
            continue
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.first_line_indent = Cm(0)
        p.paragraph_format.keep_with_next = True  # keep the caption under the image
        for inline in inlines:
            ext = inline.find(qn("wp:extent"))
            cx, cy = int(ext.get("cx")), int(ext.get("cy"))
            if cx <= max_w:
                continue
            k = max_w / cx
            for e in [ext] + inline.findall(".//" + qn("a:ext")):
                if e.get("cx") is not None:
                    e.set("cx", str(int(int(e.get("cx")) * k)))
                    e.set("cy", str(int(int(e.get("cy")) * k)))


def cover_section(doc) -> None:
    """End the cover with its own section: symmetric margins, double frame, no page number."""
    dates = [p for p in doc.paragraphs if p.style is not None and p.style.name == "CoverDate"]
    if not dates:
        return
    last = doc.sections[-1]._sectPr
    sect = copy.deepcopy(last)
    for tag in ("w:headerReference", "w:footerReference", "w:titlePg", "w:type"):
        for el in sect.findall(qn(tag)):
            sect.remove(el)
    margin = str(int(COVER_MARGIN_CM * 567))
    pgmar = sect.find(qn("w:pgMar"))
    for side in ("top", "bottom", "left", "right"):
        pgmar.set(qn(f"w:{side}"), margin)
    frame = OxmlElement("w:pgBorders")
    frame.set(qn("w:offsetFrom"), "text")
    for side, kind in FRAME.items():
        el = OxmlElement(f"w:{side}")
        el.set(qn("w:val"), kind)
        el.set(qn("w:sz"), str(FRAME_SZ))
        el.set(qn("w:space"), str(FRAME_SPACE_PT))
        el.set(qn("w:color"), "auto")
        frame.append(el)
    pgmar.addnext(frame)
    dates[-1]._p.get_or_add_pPr().append(sect)


def post_process() -> None:
    doc = Document(OUT)
    format_cover(doc)
    page_breaks(doc)
    insert_toc(doc)
    format_tables(doc)
    format_images(doc)
    section = doc.sections[-1]  # the whole document for now; the cover is split off below
    if "PAGE" not in section.footer._element.xml:
        _footer_page_number(section)
    section.different_first_page_header_footer = False
    cover_section(doc)
    doc.save(OUT)


def main() -> None:
    if not MD.exists():
        sys.exit(f"{MD} not found")
    ensure_reference()
    run_pandoc()
    post_process()
    print("built:", OUT)


if __name__ == "__main__":
    main()
